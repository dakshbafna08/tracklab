-- 1. DRIVERS TABLE (User Profiles & Credentials)
CREATE TABLE IF NOT EXISTS public.drivers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL DEFAULT 'pass',
    preferred_mode TEXT DEFAULT 'guided',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. USER STRATEGY STATE TABLE (Active Stint Selections & Pit Lap)
CREATE TABLE IF NOT EXISTS public.user_strategy_state (
    username TEXT PRIMARY KEY,
    track TEXT NOT NULL DEFAULT 'NORISRING',
    total_laps INT NOT NULL DEFAULT 72,
    stint1 TEXT NOT NULL DEFAULT 'SOFT',
    stint2 TEXT NOT NULL DEFAULT 'HARD',
    pit_lap INT NOT NULL DEFAULT 28,
    preferred_mode TEXT DEFAULT 'guided',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. RACE HISTORY TABLE (Saved Telemetry & Simulation Runs)
CREATE TABLE IF NOT EXISTS public.race_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    track TEXT NOT NULL DEFAULT 'NORISRING',
    track_name TEXT NOT NULL DEFAULT 'Norisring — Nuremberg Street Circuit',
    stint1 TEXT NOT NULL,
    stint2 TEXT NOT NULL,
    pit_lap INT NOT NULL,
    total_time NUMERIC NOT NULL,
    optimal_time NUMERIC NOT NULL,
    optimal_stint1 TEXT DEFAULT 'MEDIUM',
    optimal_stint2 TEXT DEFAULT 'HARD',
    optimal_pit_lap INT DEFAULT 28,
    gap NUMERIC NOT NULL,
    data_source TEXT DEFAULT 'MODELED_PHYSICS',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS) on all tables
ALTER TABLE public.drivers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_strategy_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.race_history ENABLE ROW LEVEL SECURITY;

-- Anonymous Public Policies (Allows seamless read, insert & update via anon key)
DROP POLICY IF EXISTS "Allow anon read on drivers" ON public.drivers;
DROP POLICY IF EXISTS "Allow anon insert on drivers" ON public.drivers;
DROP POLICY IF EXISTS "Allow anon update on drivers" ON public.drivers;
CREATE POLICY "Allow anon read on drivers" ON public.drivers FOR SELECT USING (true);
CREATE POLICY "Allow anon insert on drivers" ON public.drivers FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anon update on drivers" ON public.drivers FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow anon read on user_strategy_state" ON public.user_strategy_state;
DROP POLICY IF EXISTS "Allow anon insert on user_strategy_state" ON public.user_strategy_state;
DROP POLICY IF EXISTS "Allow anon update on user_strategy_state" ON public.user_strategy_state;
CREATE POLICY "Allow anon read on user_strategy_state" ON public.user_strategy_state FOR SELECT USING (true);
CREATE POLICY "Allow anon insert on user_strategy_state" ON public.user_strategy_state FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anon update on user_strategy_state" ON public.user_strategy_state FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow anon read on race_history" ON public.race_history;
DROP POLICY IF EXISTS "Allow anon insert on race_history" ON public.race_history;
DROP POLICY IF EXISTS "Allow anon delete on race_history" ON public.race_history;
CREATE POLICY "Allow anon read on race_history" ON public.race_history FOR SELECT USING (true);
CREATE POLICY "Allow anon insert on race_history" ON public.race_history FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow anon delete on race_history" ON public.race_history FOR DELETE USING (true);
