-- 1. TRACKS TABLE (Circuits & Configurations)
CREATE TABLE IF NOT EXISTS public.tracks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    country TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. STRATEGIES TABLE
-- Columns: user_id, track_id, name, starting_compound, starting_fuel_kg
-- Allowed tyres: SOFT, MEDIUM, HARD, INTERMEDIATE, WET
CREATE TABLE IF NOT EXISTS public.strategies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    track_id UUID REFERENCES public.tracks(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    starting_compound TEXT NOT NULL CHECK (starting_compound IN ('SOFT', 'MEDIUM', 'HARD', 'INTERMEDIATE', 'WET')),
    starting_fuel_kg NUMERIC NOT NULL DEFAULT 105,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. PIT STOPS TABLE
-- Columns: strategy_id, stop_number, lap, new_compound
-- Allowed tyres: SOFT, MEDIUM, HARD, INTERMEDIATE, WET
CREATE TABLE IF NOT EXISTS public.pit_stops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    strategy_id BIGINT REFERENCES public.strategies(id) ON DELETE CASCADE,
    stop_number INT NOT NULL DEFAULT 1,
    lap INT NOT NULL,
    new_compound TEXT NOT NULL CHECK (new_compound IN ('SOFT', 'MEDIUM', 'HARD', 'INTERMEDIATE', 'WET')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. PROFILES TABLE (Linked with Supabase Auth)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
-- Row Level Security (RLS) Policies
-- =========================================================================
ALTER TABLE public.tracks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.strategies ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pit_stops ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Tracks (Public Read)
CREATE POLICY "Allow public read on tracks" ON public.tracks FOR SELECT USING (true);

-- Strategies (Authenticated User & Anon Fallback)
CREATE POLICY "Allow authenticated read own strategies" ON public.strategies FOR SELECT USING (true);
CREATE POLICY "Allow authenticated insert own strategies" ON public.strategies FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow authenticated delete own strategies" ON public.strategies FOR DELETE USING (true);

-- Pit Stops (Authenticated User & Anon Fallback)
CREATE POLICY "Allow read on pit_stops" ON public.pit_stops FOR SELECT USING (true);
CREATE POLICY "Allow insert on pit_stops" ON public.pit_stops FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow delete on pit_stops" ON public.pit_stops FOR DELETE USING (true);

-- Profiles (Public Read & Self Update)
CREATE POLICY "Allow read on profiles" ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Allow insert on profiles" ON public.profiles FOR INSERT WITH CHECK (true);
